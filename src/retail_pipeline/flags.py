"""Flag taxonomy: which issue codes block a record (review queue) and which only warn."""


BLOCKING_FLAGS = {
    "INVALID_ORDER_ID", "TS_AMBIGUOUS_NO_TZ", "TS_AMBIGUOUS_DATE_ORDER", "TS_INVALID", "TS_MISSING",
    "TS_DST_AMBIGUOUS", "TS_DST_NONEXISTENT",
    "INVALID_QTY", "QTY_OUT_OF_RANGE", "UNIT_UNKNOWN", "INVALID_PRICE", "PRICE_OUT_OF_RANGE", "DISCOUNT_INVALID",
    "SKU_UNKNOWN", "CURRENCY_UNKNOWN", "CURRENCY_SYMBOL_CONFLICT", "STATUS_UNKNOWN",
    "RETURN_ON_ORDER_LINE", "CONFLICTING_DUPLICATE",
}

WARNING_FLAGS = {
    "DISCOUNT_UNKNOWN", "FX_UNAVAILABLE", "SKU_RESOLVED_VIA_NAME",
    "CURRENCY_INFERRED_FROM_SYMBOL", "CUSTOMER_ID_MISSING", "CUSTOMER_UNMATCHED", "CHANNEL_UNMAPPED",
    "COUNTRY_UNMAPPED", "TS_TZ_ASSUMED", "TS_DATE_ORDER_ASSUMED", "PRICE_ROUNDED",
    "SHIPPING_INVALID", "TAX_INVALID", "STATE_UNMAPPED", "POSTAL_INVALID",
    "PROMO_UNKNOWN_CODE", "PROMO_EXPIRED", "PROMO_REJECTED", "PROMO_UNVERIFIABLE", "PROMO_NO_DISCOUNT",
}

def severity(code): return "BLOCKING" if code in BLOCKING_FLAGS else "WARNING"
